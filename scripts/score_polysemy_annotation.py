"""Score the filled polysemy human-annotation forms (the human pilot on the v3 set).

Two analyses, both gated on how many forms are actually filled in:

  1. Human inter-annotator reliability — Krippendorff's α (ordinal) across the 5
     coders. This is the *human ceiling*: how reproducible the sense-salience
     judgement is between people. It bounds how high any encoder could score.

  2. Gold-vs-encoder agreement — aggregate the coders into a per-sense gold
     salience (median across annotators), then, per word, Spearman ρ and
     winner-agreement between the gold ranking and each encoder's sense-similarity
     ranking (`sense_sims:<encoder>` from a polysemy run's metrics.json). Reported
     for the student (m2v_potion) and the teacher (LaBSE). This is the human-
     ceiling context for the cross-encoder ρ already reported in §4.3.

The forms are generated by build_polysemy_form.py: sheet "Form", one row per
(word, sense) in dataset order, columns
    kelime_no | kelime | anlam_no | toplam_anlam | tanim | ornek_cumle | PUAN_0_3 | NOT
Annotators fill only PUAN_0_3 (0-3) and optionally NOT. A blank PUAN means
"bilmiyorum" (don't know) and is treated as missing — NOT as 0.

SKELETON STATUS: runs today against the empty forms and reports fill status; the
α and gold-vs-encoder blocks light up automatically as forms come back filled.

Usage:
    python scripts/score_polysemy_annotation.py \
        --encoder-metrics results/polysemy/<primary_run>/metrics.json
"""
from __future__ import annotations

import argparse
import csv
import glob
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from distillprobe.metrics.stats import bootstrap_ci  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
# Default input is the committed, de-identified ratings CSV (no PII) so the
# analysis reproduces from the repo alone. The raw filled xlsx forms carry
# annotator names/ages and are kept local under annotation/responses/ (gitignored);
# point --forms-glob there to re-derive the CSV.
RATINGS_CSV = str(ROOT / "annotation" / "polysemy_ratings_anon.csv")
FORMS_GLOB = str(ROOT / "annotation" / "responses" / "polysemy_form_annotator_*.xlsx")
SCALE_MIN, SCALE_MAX = 0, 3


def load_ratings_csv(path: str) -> dict[str, dict[tuple[int, int], float]]:
    """Read the anonymized ratings CSV → {coder: {(kelime_no, anlam_no): score|nan}}."""
    META_COLS = {"kelime_no", "kelime", "anlam_no", "tanim"}
    with open(path, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        coder_cols = [c for c in reader.fieldnames or [] if c not in META_COLS]
        coders: dict[str, dict[tuple[int, int], float]] = {c: {} for c in coder_cols}
        for row in reader:
            key = (int(row["kelime_no"]), int(row["anlam_no"]))
            for c in coder_cols:
                raw = row[c]
                coders[c][key] = float(raw) if raw not in (None, "") else float("nan")
    return coders


# --------------------------------------------------------------------------- io
def _coder_label(path: str) -> str:
    return Path(path).stem.replace("polysemy_form_annotator_", "")


def load_form(path: str) -> dict[tuple[int, int], float]:
    """Return {(kelime_no, anlam_no): score|nan} for one annotator workbook."""
    from openpyxl import load_workbook  # local import: only needed in xlsx mode

    ws = load_workbook(path, data_only=True)["Form"]
    scores: dict[tuple[int, int], float] = {}
    for row in ws.iter_rows(min_row=2, values_only=True):
        if not row or row[1] is None:  # col 1 = kelime
            continue
        kelime_no, _kelime, anlam_no = row[0], row[1], row[2]
        raw = row[6]  # PUAN_0_3
        key = (int(kelime_no), int(anlam_no))
        if raw is None or (isinstance(raw, str) and not raw.strip()):
            scores[key] = float("nan")
            continue
        try:
            val = float(raw)
        except (TypeError, ValueError):
            print(f"  [warn] {_coder_label(path)} {key}: non-numeric PUAN {raw!r} -> missing",
                  file=sys.stderr)
            scores[key] = float("nan")
            continue
        if not (SCALE_MIN <= val <= SCALE_MAX):
            print(f"  [warn] {_coder_label(path)} {key}: PUAN {val} out of 0-3 -> clipped-flagged",
                  file=sys.stderr)
        scores[key] = val
    return scores


# ------------------------------------------------------------------- analysis 1
def krippendorff_alpha(matrix: np.ndarray) -> float:
    """Ordinal Krippendorff α over a (coders x units) matrix with np.nan missing."""
    import krippendorff  # local import: optional dep

    return float(krippendorff.alpha(reliability_data=matrix, level_of_measurement="ordinal"))


# ------------------------------------------------------------------- analysis 2
def gold_vs_encoder(
    gold_by_word: dict[str, list[float]],
    encoder_sims: dict[str, list[float]],
    *,
    seed: int = 42,
    bootstrap_n: int = 10_000,
) -> dict[str, Any] | None:
    """Per-word Spearman ρ + winner-agreement between gold and one encoder."""
    from scipy.stats import spearmanr

    rhos: list[float] = []
    winner_hits = 0
    winner_tot = 0
    for word, gold in gold_by_word.items():
        sims = encoder_sims.get(word)
        if sims is None or len(sims) != len(gold):
            continue
        g = np.asarray(gold, dtype=np.float64)
        s = np.asarray(sims, dtype=np.float64)
        mask = ~(np.isnan(g) | np.isnan(s))
        if mask.sum() < 2:
            continue
        rho, _ = spearmanr(g[mask], s[mask])
        if not np.isnan(rho):
            rhos.append(rho)
        # winner agreement: does the gold-top sense match the encoder-top sense?
        winner_tot += 1
        if int(np.argmax(np.where(mask, g, -np.inf))) == int(np.argmax(np.where(mask, s, -np.inf))):
            winner_hits += 1
    if not rhos:
        return None
    arr = np.asarray(rhos, dtype=np.float64)
    ci = bootstrap_ci(arr, n=bootstrap_n, seed=seed)
    return {
        "n_words": len(rhos),
        "mean_spearman": float(arr.mean()),
        "spearman_ci_low": ci.low,
        "spearman_ci_high": ci.high,
        "winner_agreement_rate": winner_hits / winner_tot if winner_tot else float("nan"),
    }


# --------------------------------------------------------------------------- main
def _mean_pairwise_word_rho(
    coders: dict[str, dict[tuple[int, int], float]],
    active: list[str],
    units: list[tuple[int, int]],
) -> tuple[float, int] | None:
    """Mean per-word Spearman ρ between every pair of annotators.

    Computed per word (over that word's senses) and then averaged, mirroring how
    the gold-vs-encoder correlation is computed, so the human--human and
    human--encoder numbers are directly comparable.
    """
    from scipy.stats import spearmanr

    by_word: dict[int, list[tuple[int, int]]] = {}
    for kel_no, an_no in units:
        by_word.setdefault(kel_no, []).append((kel_no, an_no))

    per_pair: list[float] = []
    for a_i in range(len(active)):
        for b_i in range(a_i + 1, len(active)):
            a, b = coders[active[a_i]], coders[active[b_i]]
            word_rhos: list[float] = []
            for keys in by_word.values():
                if len(keys) < 3:
                    continue
                xs = np.array([a.get(k, np.nan) for k in keys], dtype=float)
                ys = np.array([b.get(k, np.nan) for k in keys], dtype=float)
                mask = ~np.isnan(xs) & ~np.isnan(ys)
                if mask.sum() < 3:
                    continue
                x, y = xs[mask], ys[mask]
                # Spearman is undefined when either side has no variance.
                if len(set(x.tolist())) < 2 or len(set(y.tolist())) < 2:
                    continue
                rho, _ = spearmanr(x, y)
                if not np.isnan(rho):
                    word_rhos.append(float(rho))
            if word_rhos:
                per_pair.append(float(np.mean(word_rhos)))
    if not per_pair:
        return None
    return float(np.mean(per_pair)), len(per_pair)


def _dataset_path(explicit: str | None) -> Path:
    """Resolve the word/sense-order source.

    Only the word list and the per-word sense count are needed here, and the
    released sense manifest carries both. The full dataset embeds TDK's
    copyrighted glosses and is therefore export-ignored from the release, so
    falling back to the manifest is what makes this script runnable straight
    from the public archive (Appendix A names it as the reproducer of the
    human-ceiling figures).
    """
    if explicit:
        p = Path(explicit)
        if not p.exists():
            raise SystemExit(f"--dataset not found: {p}")
        return p
    full = ROOT / "data" / "polysemy" / "tr_polysemy.v3.json"
    if full.exists():
        return full
    manifest = ROOT / "data" / "polysemy" / "tr_polysemy.v3.sense_manifest.json"
    if manifest.exists():
        return manifest
    raise SystemExit(
        "neither tr_polysemy.v3.json nor its sense manifest was found under "
        f"{ROOT / 'data' / 'polysemy'}; rebuild the dataset with "
        "scripts/build_polysemy_dataset.py --manifest <manifest>"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ratings-csv", default=RATINGS_CSV,
                    help="anonymized ratings CSV (default input; no PII)")
    ap.add_argument("--forms-glob", default=None,
                    help="raw filled xlsx forms (overrides --ratings-csv; PII, local only)")
    ap.add_argument("--dataset", default=None,
                    help="dataset for word/sense order in gold-vs-encoder; defaults to "
                         "tr_polysemy.v3.json, falling back to the released sense "
                         "manifest (which carries the same word order and sense counts "
                         "without TDK's copyrighted glosses)")
    ap.add_argument("--encoder-metrics", default=None,
                    help="path to a polysemy run metrics.json (for gold-vs-encoder)")
    ap.add_argument("--gold-agg", choices=["median", "mean"], default="median")
    ap.add_argument("--out", default=None, help="optional path to write a JSON report")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    if args.forms_glob:
        form_paths = sorted(glob.glob(args.forms_glob))
        if not form_paths:
            print(f"no forms matched {args.forms_glob}", file=sys.stderr)
            return 1
        coders = {_coder_label(p): load_form(p) for p in form_paths}
    elif Path(args.ratings_csv).exists():
        coders = load_ratings_csv(args.ratings_csv)
        print(f"[input] {args.ratings_csv} ({len(coders)} coders)")
    else:
        print(f"no input: {args.ratings_csv} missing and no --forms-glob given", file=sys.stderr)
        return 1
    # Canonical unit order: the union of keys, sorted (kelime_no, anlam_no).
    units = sorted({k for s in coders.values() for k in s})
    coder_names = list(coders.keys())

    # --- fill-status report --------------------------------------------------
    print("=" * 64)
    print("POLYSEMY ANNOTATION — fill status")
    print("=" * 64)
    filled_per_coder = {}
    for c in coder_names:
        n_filled = sum(1 for k in units if not np.isnan(coders[c].get(k, float("nan"))))
        filled_per_coder[c] = n_filled
        print(f"  coder {c}: {n_filled}/{len(units)} senses scored")
    active = [c for c in coder_names if filled_per_coder[c] > 0]
    print(f"  -> {len(active)}/{len(coder_names)} forms have any data; {len(units)} senses total")

    report: dict[str, Any] = {
        "n_units": len(units),
        "coders": coder_names,
        "filled_per_coder": filled_per_coder,
    }

    if len(active) < 2:
        print("\n[skipped] need ≥2 filled forms for Krippendorff α and gold-vs-encoder.")
        print("          (skeleton ready — re-run once annotators return their forms.)")
        if args.out:
            Path(args.out).write_text(json.dumps(report, indent=2, ensure_ascii=False), "utf-8")
        return 0

    # --- analysis 1: Krippendorff α -----------------------------------------
    matrix = np.full((len(active), len(units)), np.nan, dtype=np.float64)
    for i, c in enumerate(active):
        for j, k in enumerate(units):
            matrix[i, j] = coders[c].get(k, float("nan"))
    alpha = krippendorff_alpha(matrix)
    report["krippendorff_alpha_ordinal"] = alpha
    report["alpha_n_coders"] = len(active)
    print("\n" + "-" * 64)
    print(f"Krippendorff α (ordinal, {len(active)} coders) = {alpha:.3f}   [human ceiling]")

    # Leave-one-annotator-out α: shows the ceiling is not carried by one coder.
    loo: dict[str, float] = {}
    if len(active) > 2:
        for i, c in enumerate(active):
            sub = np.delete(matrix, i, axis=0)
            loo[c] = krippendorff_alpha(sub)
        report["krippendorff_alpha_loo"] = loo
        print(f"  leave-one-out α: {min(loo.values()):.3f}–{max(loo.values()):.3f} "
              f"({', '.join(f'−{c}:{v:.3f}' for c, v in loo.items())})")

    # Mean pairwise per-word rank correlation between annotators. This is the
    # human--human agreement the paper contrasts against human--encoder
    # agreement, so it belongs in the same reproduction path.
    pair_rhos = _mean_pairwise_word_rho(coders, active, units)
    if pair_rhos is not None:
        mean_rho, n_pairs = pair_rhos
        report["mean_pairwise_word_spearman"] = mean_rho
        print(f"  mean pairwise per-word rank ρ (human–human) = {mean_rho:.3f} "
              f"over {n_pairs} annotator pairs")

    # --- gold aggregation ----------------------------------------------------
    agg = np.nanmedian if args.gold_agg == "median" else np.nanmean
    gold_unit: dict[tuple[int, int], float] = {}
    for j, k in enumerate(units):
        col = matrix[:, j]
        gold_unit[k] = float(agg(col)) if np.any(~np.isnan(col)) else float("nan")

    # group gold by word, in sense order (anlam_no ascending). Word names and
    # sense counts come from the dataset (kelime_no = 1-based word index).
    gold_by_word: dict[str, list[float]] = {}
    ds_words = json.loads(_dataset_path(args.dataset).read_text(encoding="utf-8"))["words"]
    word_of = {i: w["word"] for i, w in enumerate(ds_words, 1)}
    senses_of = {i: list(range(1, len(w["senses"]) + 1)) for i, w in enumerate(ds_words, 1)}
    for kel_no, word in word_of.items():
        gold_by_word[word] = [gold_unit[(kel_no, an)] for an in sorted(senses_of[kel_no])]

    # --- analysis 2: gold-vs-encoder ----------------------------------------
    if args.encoder_metrics:
        m = json.load(open(args.encoder_metrics, encoding="utf-8"))
        per_word = m["per_category"]
        enc_keys = sorted({k for r in per_word for k in r if k.startswith("sense_sims:")})
        print("\n" + "-" * 64)
        print(f"Gold-vs-encoder (gold = per-sense {args.gold_agg} of {len(active)} coders):")
        gve: dict[str, Any] = {}
        for ek in enc_keys:
            enc_name = ek.split(":", 1)[1]
            sims = {r["word"]: r[ek] for r in per_word if ek in r}
            res = gold_vs_encoder(gold_by_word, sims, seed=args.seed)
            if res is None:
                continue
            gve[enc_name] = res
            print(f"  {enc_name:12} ρ={res['mean_spearman']:.3f} "
                  f"[{res['spearman_ci_low']:.3f}, {res['spearman_ci_high']:.3f}]  "
                  f"winner={res['winner_agreement_rate']:.3f}  (n={res['n_words']} words)")
        report["gold_vs_encoder"] = gve
        report["gold_agg"] = args.gold_agg
        report["encoder_metrics"] = args.encoder_metrics
    else:
        print("\n[note] pass --encoder-metrics <primary metrics.json> for gold-vs-encoder ρ.")

    if args.out:
        Path(args.out).write_text(json.dumps(report, indent=2, ensure_ascii=False), "utf-8")
        print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
